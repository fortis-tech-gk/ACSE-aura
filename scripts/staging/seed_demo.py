# Heat draws (accredited regular entrants of paid squads, random order; lane races centre-first)
def entrants(code, relay=False):
    if relay:
        # A relay team can report only with 4 accredited runners (migration 0035)
        ok = set(accredited)
        return [t[0] for t in teams if t[2] == events[code][0]
                and sum(1 for m in members if m[0] == t[0] and m[1] in ok) >= 4]
    return [pid for pid, eid, kind in regs if eid == events[code][0] and kind == 'regular' and pid in set(accredited)]


heat_athletes = {}


def draw(code, stage, ids, per_heat=8, relay=False):
    ids = ids[:]
    rnd.shuffle(ids)
    n = max(1, -(-len(ids) // per_heat))
    out = []
    for h in range(n):
        hid = str(uuid.uuid4())
        chunk = ids[h::n]
        sql.append(f"INSERT INTO heats (id, event_id, schedule_item_id, stage, heat_number, status) VALUES ({q(hid)}, {q(events[code][0])}, {q(item_ids.get((code, stage)))}, {q(stage)}, {h + 1}, 'SCHEDULED');")
        lanes = [4, 5, 3, 6, 2, 7, 1, 8][:len(chunk)] if events[code][1] not in ('field_throw', 'field_horizontal_jump', 'field_vertical_jump') else list(range(1, len(chunk) + 1))
        rnd.shuffle(lanes)
        for ent, lane in zip(chunk, lanes):
            haid = str(uuid.uuid4())
            heat_athletes[(hid, ent)] = haid
            col = 'relay_team_id' if relay else 'profile_id'
            sql.append(f"INSERT INTO heat_athletes (id, heat_id, {col}, lane_number, call_room_reported) VALUES ({q(haid)}, {q(hid)}, {q(ent)}, {lane}, TRUE);")
        out.append((hid, chunk))
    return out


def track_results(heat, base, spread):
    hid, chunk = heat
    for ent in chunk:
        t = round(base + rnd.random() * spread, 2)
        sql.append(f"SELECT submit_track_result({q(heat_athletes[(hid, ent)])}, {t}, {rnd.randint(130, 190)}, 0.8, 'FINISHED', '', NULL);")
    sql.append(f"UPDATE heats SET status = 'COMPLETED', wind_reading = 0.8 WHERE id = {q(hid)};")


