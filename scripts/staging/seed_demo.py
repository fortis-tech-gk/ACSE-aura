def read_env(path):
    env = {}
    if not os.path.exists(path):
        return env
    for line in open(path):
        m = re.match(r'^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$', line)
        if m:
            env[m.group(1)] = m.group(2).strip('"').strip("'")
    return env


def ref_of(url):
    m = re.search(r'([a-z0-9]{20})', url or '')
    return m.group(1) if m else None


