// Builds src/lib/certificate-assets.ts: certificate fonts (latin woff2) + logos as base64, so the
// certificate renders identically offline and inside expo-print. Run once; commit the output.
//   node scripts/build-certificate-assets.mjs
import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const web = path.resolve(root, '..', 'web');
const sharp = createRequire(path.join(web, 'package.json'))('sharp');

const FAMILIES =
  'family=Cinzel:wght@700;800&family=Cinzel+Decorative:wght@700;900&family=Montserrat:wght@500;600;700&family=Cormorant+Garamond:ital,wght@1,600';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=block`, { headers: { 'User-Agent': UA } })).text();

const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)].filter((m) => m[1] === 'latin').map((m) => m[2]);
let fontCss = '';
for (const b of blocks) {
  const url = /url\((https:[^)]+\.woff2)\)/.exec(b)[1];
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  fontCss += b.replace(/src:[^;]+;/, `src: url(data:font/woff2;base64,${buf.toString('base64')}) format('woff2');`).replace(/\s+/g, ' ') + '\n';
}

const logo = async (p) => `data:image/png;base64,${(await sharp(readFileSync(path.join(web, p))).resize(240, 240, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png({ compressionLevel: 9 }).toBuffer()).toString('base64')}`;

writeFileSync(
  path.join(root, 'src/lib/certificate-assets.ts'),
  `// GENERATED by scripts/build-certificate-assets.mjs — do not edit by hand.\nexport const CERT_FONT_CSS = ${JSON.stringify(fontCss)};\nexport const CERT_VTU_LOGO = ${JSON.stringify(await logo('public/vtu.png'))};\nexport const CERT_ACS_LOGO = ${JSON.stringify(await logo('public/id-card/acs-logo.webp'))};\n`,
);
console.log(`${blocks.length} font faces, ${(fontCss.length / 1024).toFixed(0)} KB css`);
