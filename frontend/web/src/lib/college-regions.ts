/** Division for a college: the stored region if set, else the built-in map, else null. */
export function collegeDivision(code?: string | null, storedRegion?: string | null): VtuDivision | null {
  if (storedRegion && (VTU_DIVISIONS as readonly string[]).includes(storedRegion)) return storedRegion as VtuDivision;
  const key = String(code || '').toUpperCase();
  return CODE_TO_DIVISION[key] ?? null;
}
